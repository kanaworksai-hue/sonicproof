def entries() -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for items in VOCAB.values():
        for x in items:
            if x not in seen:
                seen.add(x)
                out.append(x)
    return out


def category_of(entry: str) -> str | None:
    for cat, items in VOCAB.items():
        if entry in items:
            return cat
    return None
